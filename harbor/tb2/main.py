#!/usr/bin/env python3
"""Terminal-Bench 2 tasks -> test-calls variants (tasks/tb2_tc/<task>__tc<N>).

The polyglot-tc model, adapted to TB2's root-assuming tasks:
- the agent runs as non-root `agent`; the hidden tests sit root-only in
  /opt/hidden-tests, and `run-tests` (sudo, no arguments) runs them up to N times,
  in place on the live /app with a snapshot/restore around each run (TB2 tests check
  and sometimes rewrite absolute /app paths, see template/run-tests-inner);
- package installs, which TB2 tasks and oracles do as root, go through
  `apt-get`/`apt`/`sudo` shims to a sudo-allowed wrapper that only takes plain
  package names from the distro repos (template/pkg-install);
- the image is built FROM the task's prebuilt docker_image plus Claude Code (pinned,
  as polyglot-tc), sudo, and a root-owned offline pytest venv for grading. Where the
  image ships uv, the agent's own uv also gets the Python the tests' venv uses
  (python-build-standalone downloads come from github, which the allowlist blocks);
- tests/test.sh is replaced by template/test.sh (same test file, venv pytest -v,
  reward.json with tests_* and the run-tests call fields via the polyglot fork's
  count_tests.sh).

usage: main.py --src <terminal-bench-2 checkout> --tasks a,b,c --test-calls N [--output-dir DIR]
"""
import argparse
import re
import shutil
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
TPL = HERE / "template"
POLYGLOT_TPL = HERE.parent / "aider_polyglot" / "task-template"

# same agent allowlist as polyglot-tc (task-template/task.toml) plus the distro mirrors
# pkg-install needs; github stays blocked (TB2's tests and solutions are on it)
ALLOWED_HOSTS = [
    "192.168.0.0/16", "172.16.0.0/12",
    "pypi.org", "files.pythonhosted.org",
    "registry.npmjs.org",
    "crates.io", "index.crates.io", "static.crates.io",
    "proxy.golang.org", "sum.golang.org",
    "repo.maven.apache.org", "repo1.maven.org",
    "deb.debian.org", "security.debian.org",
    "archive.ubuntu.com", "security.ubuntu.com", "ports.ubuntu.com",
    "docs.python.org",
]
PY = "3.13"   # what upstream's test.sh runs pytest under (uvx -p 3.13)


def cc_version() -> str:
    m = re.search(r"^ARG CC_VERSION=(\S+)", (POLYGLOT_TPL / "Dockerfile").read_text(), re.M)
    return m.group(1)


def test_setup(test_sh: str) -> dict:
    """How upstream's test.sh runs pytest. Two shapes: `uvx -w pkg ...` (an isolated
    python {PY}) or `pip install pkg ...` into the image's own python, which the tests
    then need (they import what the task installed there). Plus `cp /tests/x /app/x`
    setup steps and, for repo-fix tasks, a gate on the repo's own test suite (a pytest
    run with no /tests/ path)."""
    pip = re.search(r"^\s*pip3? install (.+)$", test_sh, re.M)
    runs = re.findall(r"^\s*(?:python3? -m )?pytest (.+)$", test_sh, re.M)
    return {
        "mode": "pip" if pip else "uvx",
        "deps": pip.group(1).split() if pip else re.findall(r"-w\s+(\S+)", test_sh),
        "pre": [f'cp "$TEST_DIR/{m.group(1)}" {m.group(2)}'
                for m in re.finditer(r"^\s*cp /tests/(\S+) (\S+)\s*$", test_sh, re.M)],
        "repo_suite": any("/tests/" not in r for r in runs),
    }


def test_apt_pkgs(test_sh: str) -> list[str]:
    """Packages upstream's test.sh apt-installs at grading time (git, gcc, expect, ...);
    baked into the image since grading here runs offline. The agent sees them too."""
    pkgs = []
    for line in re.findall(r"apt-get install -y (.+)", test_sh):
        pkgs += [p for p in line.split() if p != "curl" and p not in pkgs]
    return pkgs


def grading_setup(ts: dict) -> str:
    deps = " ".join(ts["deps"])
    if ts["mode"] == "pip":
        return f"""# grading: pytest in the image's own python, as upstream (offline at grading time);
# /opt/tb-pybin = that python. Root-owned site-packages: the agent can't alter it
RUN ln -s "$(command -v python || command -v python3)" /opt/tb-pybin \\
    && (/opt/tb-pybin -m pip install --no-cache-dir {deps} \\
        || /opt/tb-pybin -m pip install --no-cache-dir --break-system-packages {deps})
"""
    return f"""# grading: root-owned, offline pytest venv (upstream test.sh installs uv+pytest per run)
RUN curl -LsSf https://astral.sh/uv/0.9.5/install.sh | env UV_INSTALL_DIR=/opt/tb-uv UV_NO_MODIFY_PATH=1 sh \\
    && UV_PYTHON_INSTALL_DIR=/opt/tb-python /opt/tb-uv/uv venv -p {PY} /opt/tb-pytest \\
    && /opt/tb-uv/uv pip install --python /opt/tb-pytest/bin/python {deps} \\
    && chmod -R go-w /opt/tb-*   # tb-python only when the image has no python {PY} of its own
"""


def pytest_cmd(ts: dict) -> str:
    return "/opt/tb-pybin -m pytest" if ts["mode"] == "pip" else "/opt/tb-pytest/bin/python -m pytest"


def dockerfile(image: str, ts: dict, apt_pkgs: list[str]) -> str:
    return f"""# (tb2_tc) generated by harbor/tb2/main.py
FROM {image}
USER root
RUN apt-get update && apt-get install -y --no-install-recommends curl ca-certificates sudo procps {' '.join(apt_pkgs)} \\
    && rm -rf /var/lib/apt/lists/* \\
    && rm -f /etc/dpkg/dpkg.cfg.d/excludes /etc/dpkg/dpkg.cfg.d/docker   # slim images: keep docs/man pages of later installs

# pinned Claude Code, as polyglot-tc (Harbor skips its per-trial install when it matches)
ARG CC_VERSION={cc_version()}
RUN curl -fsSL https://downloads.claude.ai/claude-code-releases/bootstrap.sh | bash -s -- $CC_VERSION \\
    && cp -L /root/.local/bin/claude /usr/local/bin/claude && rm -rf /root/.local/share/claude /root/.local/bin/claude \\
    && claude --version | grep -q "^$CC_VERSION"

{grading_setup(ts)}
RUN useradd -m -s /bin/bash agent \\
    && if command -v uv >/dev/null; then runuser -u agent -- env HOME=/home/agent uv python install {PY}; fi
COPY hidden-tests/ /opt/hidden-tests/
COPY run-tests/ /opt/run-tests/
COPY shims/ /opt/tb-shims/
RUN chown -R root:root /opt/hidden-tests && chmod 700 /opt/hidden-tests \\
    && mv /opt/run-tests/run-tests /usr/local/bin/run-tests \\
    && chmod 755 /usr/local/bin/run-tests /opt/run-tests /opt/run-tests/run-tests-inner \\
    && chmod 644 /opt/run-tests/limit \\
    && mkdir -p /var/lib/run-tests && chmod 755 /var/lib/run-tests \\
    && install -m 755 /opt/tb-shims/pkg-install /usr/local/sbin/pkg-install \\
    && install -m 755 /opt/tb-shims/apt-shim /usr/local/bin/apt-get \\
    && install -m 755 /opt/tb-shims/apt-shim /usr/local/bin/apt \\
    && install -m 755 /opt/tb-shims/sudo-shim /usr/local/bin/sudo \\
    && rm -rf /opt/tb-shims \\
    && printf '%s\\n' 'Defaults:agent !requiretty' \\
       'agent ALL=(root) NOPASSWD: /opt/run-tests/run-tests-inner, /usr/local/sbin/pkg-install' \\
       > /etc/sudoers.d/run-tests && chmod 440 /etc/sudoers.d/run-tests \\
    && chown -R agent:agent /app
"""


def edit_toml(text: str, name: str, limit: int) -> str:
    text = re.sub(r'^(name = "[^"]+)"', rf'\1__tc{limit}"', text, count=1, flags=re.M)
    text = re.sub(r"^docker_image = .*\n", "", text, flags=re.M)        # build our Dockerfile
    text = re.sub(r"^allow_internet = .*\n", "", text, flags=re.M)      # deprecated; agent allowlist below
    text = text.replace("[metadata]\n", f"[metadata]\ntest_calls = {limit}\nsource = \"terminal-bench-2\"\n", 1)
    hosts = ", ".join(f'"{h}"' for h in ALLOWED_HOSTS)
    text = text.replace(
        "[agent]\n",
        f'[agent]\nuser = "agent"\nnetwork_mode = "allowlist"\nallowed_hosts = [{hosts}]\n', 1)
    return text


def gen(src: Path, out_root: Path, task: str, limit: int) -> Path:
    s = src / task
    cfg = tomllib.loads((s / "task.toml").read_text())
    image = cfg["environment"]["docker_image"]
    out = out_root / f"{task}__tc{limit}"
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(s / "solution", out / "solution")

    up_test_sh = (s / "tests" / "test.sh").read_text()
    ts = test_setup(up_test_sh)
    tests = out / "tests"
    # every upstream test file (helpers like cancel-async-tasks' test.py too), our test.sh
    shutil.copytree(s / "tests", tests, ignore=shutil.ignore_patterns("test.sh"))
    (tests / "test.sh").write_text((TPL / "test.sh").read_text()
                                   .replace("@PYTEST@", pytest_cmd(ts))
                                   .replace("@PRE@", "\n".join(ts["pre"]))
                                   .replace("@REPO_SUITE@", "1" if ts["repo_suite"] else "0"))
    shutil.copy(POLYGLOT_TPL / "count_tests.sh", tests)
    n_tests = len(re.findall(r"^\s*def test_", (s / "tests" / "test_outputs.py").read_text(), re.M))
    (tests / "expected_total").write_text(f"{n_tests + ts['repo_suite']}\n")

    env = out / "environment"
    shutil.copytree(tests, env / "hidden-tests")
    rt = env / "run-tests"
    rt.mkdir()
    # agent side: the polyglot-tc wrapper, sudo'ing to root instead of `tester`
    outer = (POLYGLOT_TPL / "run-tests" / "run-tests").read_text()
    (rt / "run-tests").write_text(outer.replace("sudo -n -u tester ", "/usr/bin/sudo -n "))
    shutil.copy(TPL / "run-tests-inner", rt)
    (rt / "limit").write_text(f"{limit}\n")
    sh = env / "shims"
    sh.mkdir()
    for f in ("pkg-install", "apt-shim", "sudo-shim"):
        shutil.copy(TPL / f, sh)
    (env / "Dockerfile").write_text(dockerfile(image, ts, test_apt_pkgs(up_test_sh)))

    (out / "task.toml").write_text(edit_toml((s / "task.toml").read_text(), task, limit))
    minutes = round(cfg["agent"]["timeout_sec"] / 60)
    (out / "instruction.md").write_text((s / "instruction.md").read_text().rstrip("\n") + f"""

## Environment and grading

You are not root in this environment, but `apt-get install <packages>` works (with
or without sudo), and so do `apt-get source <package>` / `apt-get download <package>`
for a package's source code. Installed man pages and -doc packages are available.
Internet access is blocked except for the package registries (PyPI, npm, crates.io,
Go, Maven), the distro package mirrors, and docs.python.org.

Your time limit is {minutes} minutes; when it runs out your session ends and your
work is graded as it is. Grading uses hidden tests and gives partial credit for
each test that passes, so get a working version of the required output in place
early and improve it from there.

You can check your work against the hidden tests (you cannot read them) by
running `run-tests` in a shell. You have {limit} test runs in total. After your
{limit}th run your session ends immediately and your work is graded as it is at that
moment. Each run's output is also saved to /var/lib/run-tests/run-<N>.txt.
""")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True, type=Path)
    ap.add_argument("--tasks", required=True)
    ap.add_argument("--test-calls", required=True, type=int)
    ap.add_argument("--output-dir", type=Path, default=HERE.parent / "tasks" / "tb2_tc")
    a = ap.parse_args()
    for t in a.tasks.split(","):
        print("Generated", gen(a.src, a.output_dir, t, a.test_calls))


if __name__ == "__main__":
    main()
