#!/usr/bin/env python3
"""TermGrade tasks (huggingface ai-and/termgrade-environments) -> test-calls variants
(tasks/termgrade_tc/<task>__tc<N>), the tb2_tc model (see tb2/main.py) with these
differences:
- source is the release's task_source.jsonl (each task's instruction, tests, setup.sh,
  Dockerfile and solution inline) plus base_image/Dockerfile;
- every task Dockerfile is FROM a locally built `dsbase-venv312:local`; that base is
  inlined here instead, so Harbor's per-trial builds need nothing pre-tagged;
- the base already has the grading pytest, a root-owned venv at /opt/verifier_venv
  (--system-site-packages over the image's python, which the agent can't write to);
- tests run from `cd /` as upstream's test.sh does; setup.sh's top-level work dirs
  (/data, /workdir, ...) are given to the agent along with /app;
- the tasks carry no time limit (graded with a 12h cap); DEFAULT_TIMEOUT is ours.

Pick tasks with `split == "unseen"` only: the other 202 trained/validated the
publisher's model. Selection criteria: the header of lists/termgrade.txt.

usage: main.py --src <termgrade-environments dir> --tasks a,b,c --test-calls N [--output-dir DIR]
"""
import argparse
import json
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "tb2"))
import main as tb2  # noqa: E402

DEFAULT_TIMEOUT = 900
PYTEST = "/opt/verifier_venv/bin/python -m pytest"
SYSTEM_DIRS = {"tests", "tmp", "usr", "etc", "root", "var", "opt", "bin", "lib", "home", "app", "solution"}


def load(src: Path, task: str) -> dict:
    with open(src / "task_source.jsonl") as f:
        for line in f:
            d = json.loads(line)
            if d["task"] == task:
                return d
    raise SystemExit(f"{task}: not in {src}/task_source.jsonl")


def work_dirs(setup_sh: str) -> list[str]:
    """Top-level dirs setup.sh creates besides /app (the task's data/output dirs)."""
    dirs = []
    for args in re.findall(r"^\s*mkdir -p (.+)$", setup_sh, re.M):
        for p in args.split():
            m = re.match(r"/([A-Za-z0-9_.-]+)", p)
            if m and m.group(1) not in SYSTEM_DIRS and f"/{m.group(1)}" not in dirs:
                dirs.append(f"/{m.group(1)}")
    return dirs


def head(src: Path, task_dockerfile: str) -> str:
    base = [l for l in (src / "base_image" / "Dockerfile").read_text().splitlines()
            if not l.startswith("#")]
    body = [l for l in task_dockerfile.splitlines() if not l.startswith("FROM ")]
    return "\n".join(["# (termgrade_tc) generated by harbor/termgrade/main.py",
                      "# --- base_image/Dockerfile (dsbase-venv312), inlined ---", *base,
                      "# --- the task's own Dockerfile ---", *body,
                      "# --- test-calls setup (tb2/main.py) ---"])


def gen(src: Path, out_root: Path, task: str, limit: int) -> Path:
    d = load(src, task)
    out = out_root / f"{task}__tc{limit}"
    if out.exists():
        shutil.rmtree(out)
    (out / "solution").mkdir(parents=True)
    (out / "solution" / "solve.sh").write_text(d["solution_sh"])

    tests = out / "tests"
    tests.mkdir()
    (tests / "test_outputs.py").write_text(d["test_outputs_py"])
    (tests / "test.sh").write_text((tb2.TPL / "test.sh").read_text()
                                   .replace("@PYTEST@", PYTEST).replace("@CWD@", "/")
                                   .replace("@PRE@", "").replace("@REPO_SUITE@", "0"))
    shutil.copy(tb2.POLYGLOT_TPL / "count_tests.sh", tests)
    n_tests = len(re.findall(r"^\s*def test_", d["test_outputs_py"], re.M))
    (tests / "expected_total").write_text(f"{n_tests}\n")

    env = out / "environment"
    shutil.copytree(tests, env / "hidden-tests")
    (env / "setup.sh").write_text(d["setup_sh"])
    rt = env / "run-tests"
    rt.mkdir()
    outer = (tb2.POLYGLOT_TPL / "run-tests" / "run-tests").read_text()
    (rt / "run-tests").write_text(outer.replace("sudo -n -u tester ", "/usr/bin/sudo -n "))
    shutil.copy(tb2.TPL / "run-tests-inner", rt)
    (rt / "limit").write_text(f"{limit}\n")
    sh = env / "shims"
    sh.mkdir()
    for f in ("pkg-install", "apt-shim", "sudo-shim"):
        shutil.copy(tb2.TPL / f, sh)
    df = tb2.dockerfile("", None, [], agent_py=None, head=head(src, d["dockerfile"]))
    dirs = work_dirs(d["setup_sh"])
    if dirs:
        df = df.rstrip("\n") + f" {' '.join(dirs)}\n"   # extends the final chown -R agent /app
    (env / "Dockerfile").write_text(df)

    hosts = ", ".join(f'"{h}"' for h in tb2.ALLOWED_HOSTS)
    (out / "task.toml").write_text(f"""schema_version = "1.1"
artifacts = []

[task]
name = "termgrade/{task}__tc{limit}"
description = "TermGrade (ai-and/termgrade-environments) task {task}, test-calls variant"

[metadata]
test_calls = {limit}
source = "termgrade"

[verifier]
timeout_sec = 900.0

[agent]
user = "agent"
network_mode = "allowlist"
allowed_hosts = [{hosts}]
timeout_sec = {DEFAULT_TIMEOUT}.0

[environment]
build_timeout_sec = 900.0
cpus = 1
memory_mb = 2048
storage_mb = 10240
gpus = 0
mcp_servers = []
""")
    (out / "instruction.md").write_text(d["instruction"].rstrip("\n") + "\n"
                                        + tb2.env_note(DEFAULT_TIMEOUT // 60, limit))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True, type=Path)
    ap.add_argument("--tasks", required=True)
    ap.add_argument("--test-calls", required=True, type=int)
    ap.add_argument("--output-dir", type=Path, default=HERE.parent / "tasks" / "termgrade_tc")
    a = ap.parse_args()
    for t in a.tasks.split(","):
        print("Generated", gen(a.src, a.output_dir, t, a.test_calls))


if __name__ == "__main__":
    main()
